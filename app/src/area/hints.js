// נוסח ההנחיה בשורה הצפה שבמפה בחקירת שטח (שלב 5ד). ההנחיה נמצאת רק שם, לא בפאנל. [ארוך, קצר]; הקצר מוצג כשרוחב המפה קטן.
// לפני סגירה הנוסח לפי מספר הנקודות, בלי תנאי נוסף; Backspace (או Ctrl+Z) מבטל נקודה אחרונה והוא מצוין בשורה.
/** @param {number} count מספר הנקודות התקינות @param {boolean} closed הפוליגון סגור */
export function terrainHint(count, closed) {
  if (closed) return ['גרירת פינה: עריכה · Esc: סגירת הכלי', 'גרירה: עריכה · Esc: סגירה'];
  if (count === 0) return ['לחץ על המפה בפינה הראשונה של האזור', 'לחץ על המפה בפינה הראשונה'];
  if (count < 3) return ['המשך ללחוץ על פינות האזור לפי הסדר. נדרשות לפחות 3 נקודות · Backspace: ביטול נקודה', 'עוד פינות, לפחות 3 · Backspace: ביטול'];
  return ['כדי לסיים, לחץ שוב על הנקודה הראשונה או לחץ פעמיים על הנקודה האחרונה · Backspace: ביטול נקודה', 'סיום: הנקודה הראשונה או לחיצה כפולה · Backspace: ביטול'];
}
